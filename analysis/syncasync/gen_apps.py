"""gen_apps.py — render all 8 ReviewGate-R apps (4 patterns x sync/async).

Every app is generated from ONE route table (routes_read.ROUTES_READ) and ONE
service layer (core_read.py), so the 12 routes, their auth levels, and their
response payloads are identical by construction across all eight. The only thing
that varies is the dependency-acquisition layer, which is the independent
variable.

  patterns                    execution models
  -------------------------   -----------------
  P1 direct construction     sync  : def handlers, sqlite3, threadpool
  P2 framework-native DI     async : async def handlers, aiosqlite
  P3 middleware / manual
  P4 external container
                                (dependency-injector)

Held constant in every app: route table, SQL, response models, auth semantics,
read-only DB, connection-pool size, worker count, and -- for the sync arm --
the anyio threadpool limiter, so the sync arm cannot borrow unboundedly more
concurrency than the async arm's pool allows.

Run:  python gen_apps.py
"""

from __future__ import annotations

import shutil
from pathlib import Path

from core_read import DB_PATH, POOL
from routes_read import ROUTES_READ

APPS = Path(__file__).resolve().parent / "apps"
HEADER = '"""AUTO-GENERATED by gen_apps.py — do not edit by hand."""\n'

PATTERNS = ["p1_direct", "p2_depends", "p3_middleware", "p4_container"]
MODELS = ["sync", "async"]

# dependency name per auth level
DEP_FOR = {"user": "get_current_user", "editor": "require_editor", "admin": "require_admin"}


def _ind(lines, n):
    pad = " " * n
    return [pad + ln if ln.strip() else ln for ln in lines]


def _ctx(model: str) -> str:
    return "with" if model == "sync" else "async with"


def _kw(model: str) -> str:
    return "def" if model == "sync" else "async def"


def _call(svc: str, call: str, model: str) -> str:
    body = f"services.{svc}{call}"
    return f"resolve({body})" if model == "sync" else f"await {body}"


# --------------------------------------------------------------------------
# shared preamble
# --------------------------------------------------------------------------

def _preamble(model: str, title: str, container: bool = False) -> list[str]:
    conn_imp = "sync_conn" if model == "sync" else "async_conn"
    L = [
        "from fastapi import Depends, FastAPI, HTTPException, Request",
        "from contextlib import asynccontextmanager",
        "import anyio.to_thread",
        "import core_read as services",
        "from core_read import (",
        "    DB_PATH, ROLES, bearer_token, current_user, lookup_user,",
        "    require_role, resolve,",
        f"    {conn_imp} as conn_ctx,",
        ")",
        f"POOL = {POOL}",
        "",
        "def _check_db() -> None:",
        "    if not DB_PATH.exists():",
        '        raise RuntimeError(f"read-only benchmark database missing: {DB_PATH}")',
        "",
        "",
    ]
    L += [
        "@asynccontextmanager",
        "async def lifespan(app: FastAPI):",
        "    _check_db()",
    ]
    if container:
        L += [
            "    app.state.container = build_container()",
            "    yield",
            "    app.state.container = None",
        ]
    else:
        L += ["    yield"]
    if model == "sync":
        # symmetric bound: at most POOL sync handlers run at once, matching the
        # async arm's pool of POOL connections.
        L.append("    anyio.to_thread.current_default_thread_limiter().total_tokens = POOL")
    else:
        # aiosqlite keeps one non-daemon thread per connection; without this the
        # server process would not exit
        L += [
            "    from core_read import close_async_pool",
            "    await close_async_pool()",
        ]
    L += [
        "",
        "# docs_url/redoc_url/openapi_url are off so the exposed surface is exactly",
        "# the 12 read routes and nothing else -- verified by smoke.py",
        "app = FastAPI(title={!r}, lifespan=lifespan,".format(title),
        "              docs_url=None, redoc_url=None, openapi_url=None)",
        "",
    ]
    return L


# --------------------------------------------------------------------------
# P1 — direct construction (zero DI): the handler does everything itself
# --------------------------------------------------------------------------

def p1(pattern: str, model: str) -> str:
    L = _preamble(model, f"ReviewGate-R-P1-{model}")
    for _m, path, name, auth, svc, _resp, sig, call in ROUTES_READ:
        need_req = auth != "public"
        params = ("request: Request" + (", " + sig if sig else "")) if need_req else sig
        L += ["", f"@app.get({path!r})", f"{_kw(model)} {name}({params}):"]
        body = [f"{_ctx(model)} conn_ctx() as conn:"]
        indent = 4
        if need_req:
            body += ["    user = " + _call("current_user", "(conn, request)", model)]
            body += ['    require_role(user, ROLES["%s"])' % auth]
            indent = 4
        body += ["    return " + _call(svc, call, model)]
        L += _ind(body, indent)
    return HEADER + "\n".join(L) + "\n"


# --------------------------------------------------------------------------
# P2 — framework-native DI (Depends)
# --------------------------------------------------------------------------

def p2(pattern: str, model: str) -> str:
    L = _preamble(model, f"ReviewGate-R-P2-{model}")
    if model == "sync":
        L += [
            "def get_db():",
            "    with conn_ctx() as conn:",
            "        yield conn",
            "",
            "",
            "def get_current_user(request: Request, conn=Depends(get_db)) -> dict:",
            "    return resolve(current_user(conn, request))",
            "",
            "",
            "def require_editor(user: dict = Depends(get_current_user)) -> dict:",
            "    return require_role(user, ROLES['editor'])",
            "",
            "",
            "def require_admin(user: dict = Depends(get_current_user)) -> dict:",
            "    return require_role(user, ROLES['admin'])",
        ]
    else:
        L += [
            "async def get_db():",
            "    async with conn_ctx() as conn:",
            "        yield conn",
            "",
            "",
            "async def get_current_user(request: Request, conn=Depends(get_db)) -> dict:",
            "    return await current_user(conn, request)",
            "",
            "",
            "async def require_editor(user: dict = Depends(get_current_user)) -> dict:",
            "    return require_role(user, ROLES['editor'])",
            "",
            "",
            "async def require_admin(user: dict = Depends(get_current_user)) -> dict:",
            "    return require_role(user, ROLES['admin'])",
        ]
    for _m, path, name, auth, svc, _resp, sig, call in ROUTES_READ:
        deps = ["conn=Depends(get_db)"]
        if auth != "public":
            deps.append(f"user=Depends({DEP_FOR[auth]})")
        params = ", ".join(([sig] if sig else []) + deps)
        L += ["", "", f"@app.get({path!r})", f"{_kw(model)} {name}({params}):"]
        L += _ind(["return " + _call(svc, call, model)], 4)
    return HEADER + "\n".join(L) + "\n"


# --------------------------------------------------------------------------
# P3 — middleware assembles the context, handlers read request.state
# --------------------------------------------------------------------------

def p3(pattern: str, model: str) -> str:
    L = _preamble(model, f"ReviewGate-R-P3-{model}")
    L += [
        "class _Ctx:",
        "    __slots__ = ('user',)",
        "    def __init__(self, user):",
        "        self.user = user",
        "",
        "",
    ]
    if model == "sync":
        L += [
            "def _resolve_user(request: Request):",
            "    token = bearer_token(request.headers)",
            "    if not token:",
            "        return None",
            "    with conn_ctx() as conn:",
            "        u = resolve(lookup_user(conn, token))",
            "        # a suspended user is unauthenticated, matching current_user()",
            "        return None if (u and u['suspended']) else u",
            "",
            "",
            "@app.middleware('http')",
            "async def build_ctx(request: Request, call_next):",
            "    request.state.ctx = _Ctx(",
            "        await anyio.to_thread.run_sync(_resolve_user, request)",
            "    )",
            "    return await call_next(request)",
        ]
    else:
        L += [
            "async def _resolve_user(request: Request):",
            "    token = bearer_token(request.headers)",
            "    if not token:",
            "        return None",
            "    async with conn_ctx() as conn:",
            "        u = await lookup_user(conn, token)",
            "        # a suspended user is unauthenticated, matching current_user()",
            "        return None if (u and u['suspended']) else u",
            "",
            "",
            "@app.middleware('http')",
            "async def build_ctx(request: Request, call_next):",
            "    request.state.ctx = _Ctx(await _resolve_user(request))",
            "    return await call_next(request)",
        ]
    for _m, path, name, auth, svc, _resp, sig, call in ROUTES_READ:
        params = "request: Request" + (", " + sig if sig else "")
        L += ["", "", f"@app.get({path!r})", f"{_kw(model)} {name}({params}):"]
        body = ["ctx = request.state.ctx"]
        if auth != "public":
            body += [
                "if ctx.user is None:",
                '    raise HTTPException(status_code=401, detail="Not authenticated")',
                "user = ctx.user",
                'require_role(user, ROLES["%s"])' % auth,
            ]
        body += [f"{_ctx(model)} conn_ctx() as conn:"]
        body += ["    return " + _call(svc, call, model)]
        L += _ind(body, 4)
    return HEADER + "\n".join(L) + "\n"


# --------------------------------------------------------------------------
# P4 — external container (dependency-injector)
# --------------------------------------------------------------------------

def p4(pattern: str, model: str) -> str:
    L = _preamble(model, f"ReviewGate-R-P4-{model}", container=True)
    L += [
        "from dependency_injector import containers, providers",
        "",
        "",
        "class UserService:",
    ]
    if model == "sync":
        L += [
            "    def current_user(self, conn, request):",
            "        return resolve(current_user(conn, request))",
        ]
    else:
        L += [
            "    async def current_user(self, conn, request):",
            "        return await current_user(conn, request)",
        ]
    L += [
        "    def require_role(self, user, roles):",
        "        return require_role(user, roles)",
        "",
        "",
        "class Container(containers.DeclarativeContainer):",
        "    user_service = providers.Singleton(UserService)",
        "",
        "",
        "def build_container() -> Container:",
        "    return Container()",
    ]
    for _m, path, name, auth, svc, _resp, sig, call in ROUTES_READ:
        params = "request: Request" + (", " + sig if sig else "")
        L += ["", "", f"@app.get({path!r})", f"{_kw(model)} {name}({params}):"]
        body = ["c = request.app.state.container"]
        if auth != "public":
            body += [
                f"{_ctx(model)} conn_ctx() as conn:",
                # the container's service is a plain def in the sync arm and an
                # async def in the async arm, so the call is awaited only in the
                # async arm -- no resolve() wrapper here.
                "    user = " + ("c.user_service().current_user(conn, request)" if model == "sync"
                               else "await c.user_service().current_user(conn, request)"),
                '    c.user_service().require_role(user, ROLES["%s"])' % auth,
            ]
        body += [f"{_ctx(model)} conn_ctx() as conn:"]
        body += ["    return " + _call(svc, call, model)]
        L += _ind(body, 4)
    return HEADER + "\n".join(L) + "\n"


BUILDERS = {"p1_direct": p1, "p2_depends": p2, "p3_middleware": p3, "p4_container": p4}


def main() -> None:
    if APPS.exists():
        shutil.rmtree(APPS)
    APPS.mkdir(parents=True, exist_ok=True)
    (APPS / "__init__.py").write_text("")
    print(f"db    {DB_PATH}")
    print(f"pool  {POOL}")
    bad = 0
    for pattern in PATTERNS:
        for model in MODELS:
            d = APPS / pattern / model
            d.mkdir(parents=True, exist_ok=True)
            (d / "__init__.py").write_text("")
            src = BUILDERS[pattern](pattern, model)
            (d / "app.py").write_text(src)
            try:
                compile(src, str(d / "app.py"), "exec")
                status = "compiles"
            except SyntaxError as exc:
                status = f"SYNTAX ERROR line {exc.lineno}: {exc.msg}"
                bad += 1
            print(f"  {pattern}/{model:5s}  {len(src.splitlines()):3d} lines  {status}")
    raise SystemExit(1 if bad else 0)


if __name__ == "__main__":
    main()
