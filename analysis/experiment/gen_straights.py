"""gen_straights.py — render the 4 strategy apps from the shared ReviewGate core.

Each strategy is a self-contained FastAPI app exposing the identical 20 routes,
params, auth levels, and response models (from core/routes.py). Only the
dependency-acquisition layer differs:

  S0  direct construction (zero-DI):      handlers open session() + call auth funcs
  S1  framework-native DI:                Depends(get_db/get_current_user/require_*)
  S2  manual Python DI:                   middleware assembles RequestContext; handlers
                                          read it from request.state (explicit threading)
  S3  external container (dependency-injector): services + connections built by a
                                          DeclarativeContainer; handlers pull from it

Run from analysis/experiment:  python gen_straights.py
"""

from __future__ import annotations

from pathlib import Path

from core import models as m
from core.routes import ROUTES

STRAIGHTS = Path(__file__).resolve().parent / "straights"

HEADER = '"""AUTO-GENERATED by gen_straights.py — do not edit by hand."""\n'


def _indent(block: list[str], spaces: int) -> list[str]:
    pad = " " * spaces
    return [pad + ln if ln.strip() else ln for ln in block]


def module_s0() -> str:
    L = ["from fastapi import FastAPI, Request",
         "from contextlib import asynccontextmanager",
         "from core import db, models as m, runtime, services",
         "from core.auth import ROLES, current_user, require_role",
         "from core.db import session",
         "from core.routes import ROUTES",
         "",
         "@asynccontextmanager",
         "async def lifespan(app):",
         "    _ = db.init_database()",
         "    yield",
         "",
         "app = FastAPI(title='ReviewGate-S0', lifespan=lifespan)",
         ""]
    for _method, _path, name, aauth, svc, _resp, sig, call in ROUTES:
        inner = []
        if aauth != "public":
            inner += ["user = current_user(conn, request)",
                      'require_role(user, ROLES["%s"])' % aauth]
        inner += ["return services.%s%s" % (svc, call)]
        L += ["", "@app.%s('%s')" % (_method.lower(), _path),
              "def %s(request: Request%s):" % (name, ", " + sig if sig else "")]
        L += _indent(["io_sleep()", "with session() as conn:"], 4)
        L += _indent(inner, 8)
    return HEADER + "\n".join(L) + "\n"


def _s1_dep(aauth: str):
    return {"user": "get_current_user", "editor": "require_editor", "admin": "require_admin"}.get(aauth)


def module_s1() -> str:
    L = ["from fastapi import Depends, FastAPI",
         "from contextlib import asynccontextmanager",
         "from core import db, models as m, runtime, services",
         "from core.db import get_db",
         "from core.di_spine import get_current_user, require_admin, require_editor",
         "from core.routes import ROUTES",
         "",
         "@asynccontextmanager",
         "async def lifespan(app):",
         "    _ = db.init_database()",
         "    yield",
         "",
         "app = FastAPI(title='ReviewGate-S1', lifespan=lifespan)",
         ""]
    for _method, _path, name, aauth, svc, _resp, sig, call in ROUTES:
        deps = ["conn=Depends(get_db)"]
        dep = _s1_dep(aauth)
        if dep:
            deps.append("user=Depends(%s)" % dep)
        params = ", ".join([sig] + deps) if sig else ", ".join(deps)
        L += ["", "@app.%s('%s')" % (_method.lower(), _path),
              "def %s(%s):" % (name, params)]
        L += _indent(["io_sleep()", "return services.%s%s" % (svc, call)], 4)
    return HEADER + "\n".join(L) + "\n"


def module_s2() -> str:
    L = ["from fastapi import FastAPI, HTTPException, Request",
         "from contextlib import asynccontextmanager",
         "from core import auth, db, models as m, runtime, services",
         "from core.auth import ROLES, require_role",
         "from core.db import session",
         "from core.routes import ROUTES",
         "",
         "class _Ctx:",
         "    __slots__ = ('conn', 'user')",
         "    def __init__(self, conn, user):",
         "        self.conn = conn",
         "        self.user = user",
         "",
         "@asynccontextmanager",
         "async def lifespan(app):",
         "    _ = db.init_database()",
         "    yield",
         "",
         "app = FastAPI(title='ReviewGate-S2', lifespan=lifespan)",
         "",
         "@app.middleware('http')",
         "async def build_ctx(request: Request, call_next):",
         "    with session() as conn:",
         "        request.state.ctx = _Ctx(conn, auth.lookup_user(conn, auth.bearer_token(request.headers)))",
         "        response = await call_next(request)",
         "    return response",
         ""]
    for _method, _path, name, aauth, svc, _resp, sig, call in ROUTES:
        call2 = call.replace("(conn", "(ctx.conn", 1)
        body = ["ctx = request.state.ctx", "user = ctx.user"]
        if aauth != "public":
            body += ['if ctx.user is None:',
                     '    raise HTTPException(status_code=401, detail="Not authenticated")',
                     'require_role(ctx.user, ROLES["%s"])' % aauth]
        body += ["return services.%s%s" % (svc, call2)]
        L += ["", "@app.%s('%s')" % (_method.lower(), _path),
              "def %s(request: Request%s):" % (name, ", " + sig if sig else "")]
        L += _indent(["io_sleep()"] + body, 4)
    return HEADER + "\n".join(L) + "\n"


def module_s3() -> str:
    L = ["from fastapi import FastAPI, HTTPException, Request",
         "from contextlib import asynccontextmanager",
         "from core import auth, db, models as m, runtime, services",
         "from core.auth import ROLES",
         "from core.routes import ROUTES",
         "from straights.s3.container import Container",
         "",
         "@asynccontextmanager",
         "async def lifespan(app):",
         "    _ = db.init_database()",
         "    app.state.container = Container()",
         "    yield",
         "",
         "app = FastAPI(title='ReviewGate-S3', lifespan=lifespan)",
         ""]
    for _method, _path, name, aauth, svc, _resp, sig, call in ROUTES:
        inner = []
        if aauth != "public":
            inner += ["user = c.user_service().current_user(conn, request)",
                      'c.user_service().require_role(user, ROLES["%s"])' % aauth]
        inner += ["return services.%s%s" % (svc, call)]
        L += ["", "@app.%s('%s')" % (_method.lower(), _path),
              "def %s(request: Request%s):" % (name, ", " + sig if sig else "")]
        L += _indent(["io_sleep()", "with c.conn_factory() as conn:"], 4)
        L += _indent(inner, 8)
    return HEADER + "\n".join(L) + "\n"


def _init_packages() -> None:
    (STRAIGHTS / "__init__.py").write_text("")
    for s in ("s0", "s1", "s2", "s3"):
        (STRAIGHTS / s).mkdir(parents=True, exist_ok=True)
        (STRAIGHTS / s / "__init__.py").write_text("")


def main() -> None:
    _init_packages()
    for name, fn in [("s0", module_s0), ("s1", module_s1), ("s2", module_s2), ("s3", module_s3)]:
        (STRAIGHTS / name / "app.py").write_text(fn())
        print("wrote", STRAIGHTS / name / "app.py")


if __name__ == "__main__":
    main()